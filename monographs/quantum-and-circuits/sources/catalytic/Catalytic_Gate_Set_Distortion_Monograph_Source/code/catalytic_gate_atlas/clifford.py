"""Binary symplectic Clifford models and exact small-qubit censuses.

The state is the symplectic action on Pauli exponent vectors ``(x | z)``.
Global phases and Pauli translations are intentionally omitted.  The restricted
subgroup is the parabolic stabilizer of the Z Lagrangian, generated by S, CZ,
and CNOT.  The ambient model additionally permits H.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable, Sequence

from .algebra import GF2Matrix, gf2_identity, gf2_mul, gf2_matrix_to_rows
from .search import NamedGenerator, breadth_first_distances, breadth_first_with_parents, defect_distribution, reconstruct_path, zero_one_distances, zero_one_with_parents


def h_gate(n: int, qubit: int) -> GF2Matrix:
    rows = list(gf2_identity(2 * n))
    rows[qubit], rows[n + qubit] = rows[n + qubit], rows[qubit]
    return tuple(rows)


def s_gate(n: int, qubit: int) -> GF2Matrix:
    rows = list(gf2_identity(2 * n))
    rows[n + qubit] ^= 1 << qubit
    return tuple(rows)


def cnot_gate(n: int, control: int, target: int) -> GF2Matrix:
    if control == target:
        raise ValueError("control and target must be distinct")
    rows = list(gf2_identity(2 * n))
    rows[target] ^= 1 << control
    rows[n + control] ^= 1 << (n + target)
    return tuple(rows)


def cz_gate(n: int, first: int, second: int) -> GF2Matrix:
    if first == second:
        raise ValueError("qubits must be distinct")
    rows = list(gf2_identity(2 * n))
    rows[n + first] ^= 1 << second
    rows[n + second] ^= 1 << first
    return tuple(rows)


def swap_gate(n: int, first: int, second: int) -> GF2Matrix:
    if first == second:
        raise ValueError("qubits must be distinct")
    rows = list(gf2_identity(2 * n))
    rows[first], rows[second] = rows[second], rows[first]
    rows[n + first], rows[n + second] = rows[n + second], rows[n + first]
    return tuple(rows)


def parabolic_generators(n: int, *, entangling_cost: bool = False, include_swap: bool = False) -> list[NamedGenerator[GF2Matrix]]:
    local_cost = 0 if entangling_cost else 1
    two_cost = 1
    generators: list[NamedGenerator[GF2Matrix]] = []
    for qubit in range(n):
        generators.append(NamedGenerator(f"S{qubit}", s_gate(n, qubit), local_cost))
    for control in range(n):
        for target in range(n):
            if control != target:
                generators.append(NamedGenerator(f"CX{control}{target}", cnot_gate(n, control, target), two_cost))
    for first in range(n):
        for second in range(first + 1, n):
            generators.append(NamedGenerator(f"CZ{first}{second}", cz_gate(n, first, second), two_cost))
            if include_swap:
                generators.append(NamedGenerator(f"SWAP{first}{second}", swap_gate(n, first, second), two_cost))
    return generators


def ambient_generators(n: int, *, entangling_cost: bool = False, include_swap: bool = False) -> list[NamedGenerator[GF2Matrix]]:
    generators = parabolic_generators(n, entangling_cost=entangling_cost, include_swap=include_swap)
    local_cost = 0 if entangling_cost else 1
    generators.extend(NamedGenerator(f"H{qubit}", h_gate(n, qubit), local_cost) for qubit in range(n))
    return generators


def exact_census(n: int, *, entangling_cost: bool = False, include_swap: bool = False, with_witness: bool = True) -> dict[str, object]:
    size = 2 * n
    identity = gf2_identity(size)
    restricted_generators = parabolic_generators(n, entangling_cost=entangling_cost, include_swap=include_swap)
    ambient_generators_set = ambient_generators(n, entangling_cost=entangling_cost, include_swap=include_swap)
    multiply = lambda left, right: gf2_mul(left, right, size)
    weighted = entangling_cost
    if weighted:
        if with_witness:
            restricted, restricted_parents = zero_one_with_parents(identity, restricted_generators, multiply)
            ambient, ambient_parents = zero_one_with_parents(identity, ambient_generators_set, multiply)
        else:
            restricted = zero_one_distances(identity, restricted_generators, multiply)
            ambient = zero_one_distances(identity, ambient_generators_set, multiply)
            restricted_parents = ambient_parents = None
    else:
        if with_witness:
            restricted, restricted_parents = breadth_first_with_parents(identity, restricted_generators, multiply)
            ambient, ambient_parents = breadth_first_with_parents(identity, ambient_generators_set, multiply)
        else:
            restricted = breadth_first_distances(identity, restricted_generators, multiply)
            ambient = breadth_first_distances(identity, ambient_generators_set, multiply)
            restricted_parents = ambient_parents = None
    defects = [state for state in restricted if restricted[state] > ambient[state]]
    defects.sort(key=lambda state: (restricted[state] - ambient[state], restricted[state], state), reverse=True)
    result: dict[str, object] = {
        "qubits": n,
        "metric": "entangling" if entangling_cost else "total",
        "include_swap": include_swap,
        "restricted_group_size": len(restricted),
        "ambient_group_size": len(ambient),
        "restricted_diameter": max(restricted.values()),
        "ambient_diameter": max(ambient.values()),
        "defect_count": len(defects),
        "defect_distribution": {f"{a}->{b}": count for (a, b), count in defect_distribution(restricted, ambient).items()},
        "maximum_defect": max((restricted[state] - ambient[state] for state in defects), default=0),
    }
    if defects and with_witness:
        target = defects[0]
        assert restricted_parents is not None and ambient_parents is not None
        result["witness"] = {
            "matrix": gf2_matrix_to_rows(target),
            "restricted_cost": restricted[target],
            "ambient_cost": ambient[target],
            "restricted_path": reconstruct_path(target, restricted_parents),
            "ambient_path": reconstruct_path(target, ambient_parents),
        }
    return result
