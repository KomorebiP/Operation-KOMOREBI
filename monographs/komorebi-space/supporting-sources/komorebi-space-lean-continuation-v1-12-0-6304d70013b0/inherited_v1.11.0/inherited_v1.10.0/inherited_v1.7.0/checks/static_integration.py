#!/usr/bin/env python3
"""Inventory a prospective local Lean union without altering or compiling it.

This is a filename/import DAG check, not Lean elaboration, proof checking, or
an external dependency audit. Frozen source files remain unchanged.
"""
from __future__ import annotations
from pathlib import Path
from datetime import datetime, timezone
import hashlib
import heapq
import json
import re
from build_concordance import strip_comments
ROOT=Path(__file__).resolve().parents[1]
TREES={'F':ROOT/'evidence/foundations_v020','M':ROOT/'evidence/moving_v032'}


def digest(p): return hashlib.sha256(p.read_bytes()).hexdigest()


def imports(p):
    return [token for line in strip_comments(p.read_text()).splitlines()
            if line.lstrip().startswith('import ')
            for token in line.strip().split()[1:]]


def main():
    candidates={};sources={}
    for tag,base in TREES.items():
        for p in sorted((base/'KomorebiSpace').glob('*.lean')):
            name='KomorebiSpace.'+p.stem
            candidates.setdefault(name,[]).append({'tree':tag,'path':str(p.relative_to(ROOT)),'sha256':digest(p)})
            sources.setdefault(name,p)
    selected=ROOT/'evidence/selected/HilbertHolonomyRepair.lean'
    name='KomorebiSpace.'+selected.stem
    candidates.setdefault(name,[]).append({'tree':'S','path':str(selected.relative_to(ROOT)),'sha256':digest(selected)})
    sources.setdefault(name,selected)
    shared=[{'module':name,'sources':entries,'byte_identical':len({e['sha256'] for e in entries})==1}
            for name,entries in candidates.items() if len(entries)>1]
    conflicts=[s for s in shared if not s['byte_identical']]
    local={};external={};missing=[]
    for name,p in sources.items():
        imps=imports(p)
        local[name]=sorted(i for i in imps if i.startswith('KomorebiSpace.'))
        external[name]=sorted(i for i in imps if not i.startswith('KomorebiSpace.'))
        missing.extend({'module':name,'missing_import':i} for i in local[name] if i not in sources)
    remaining={name:len(local[name]) for name in sources}
    dependents={name:[] for name in sources}
    for n,deps in local.items():
        for d in deps:
            if d in dependents:dependents[d].append(n)
    ready=[n for n,c in remaining.items() if c==0];heapq.heapify(ready);order=[]
    while ready:
        n=heapq.heappop(ready);order.append(n)
        for d in dependents[n]:
            remaining[d]-=1
            if remaining[d]==0:heapq.heappush(ready,d)
    cyclic=sorted(set(sources)-set(order))
    roots=[{'tree':t,'path':str((base/'KomorebiSpace.lean').relative_to(ROOT)),
            'sha256':digest(base/'KomorebiSpace.lean'),'imports':imports(base/'KomorebiSpace.lean')}
           for t,base in TREES.items()]
    report={'status':'PASS' if not(conflicts or missing or cyclic) else 'FAIL',
            'executed_utc':datetime.now(timezone.utc).isoformat(),
            'scope':'Static local import inventory only. External imports are enumerated, not loaded or certified.',
            'unique_production_modules':len(sources),'source_copies':sum(len(v) for v in candidates.values()),
            'shared_production_modules':shared,'conflicts':conflicts,'missing_local_imports':missing,
            'cycle_or_unresolved_nodes':cyclic,'historical_roots':roots,
            'selected_source_imports':imports(selected),'external_import_names':sorted({v for values in external.values() for v in values}),
            'local_dependencies':local,'module_sources':candidates,'proposed_order':order,
            'root_policy':'Keep both historical roots. A proposed union root is a separate .lean.txt plan, not a verified Lean module.',
            'fresh_lean_compilation':False,'fresh_axiom_audit':False}
    (ROOT/'audit/static_integration.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'data/ProposedKomorebiSpace.lean.txt').write_text(
        '/-! UNCOMPILED IMPORT PLAN. Requires canonical source placement and the pinned runtime.\n'
        'Generated by checks/static_integration.py. Static resolution is not elaboration. -/\n'+
        '\n'.join('import '+n for n in order)+'\n')
    print(json.dumps({k:report[k] for k in ['status','unique_production_modules','source_copies','shared_production_modules','conflicts','missing_local_imports','cycle_or_unresolved_nodes','fresh_lean_compilation']},indent=2))
    if report['status']!='PASS':raise SystemExit(1)

if __name__=='__main__':main()
