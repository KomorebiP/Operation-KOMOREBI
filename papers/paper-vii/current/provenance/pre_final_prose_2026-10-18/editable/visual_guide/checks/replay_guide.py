#!/usr/bin/env python3
"""Replay supplied guide code in isolation and retain current bounded results.

The historical programs are copied verbatim. Original code writes only into the
isolated directory. Plot coordinate sampling is not a proof of a general claim.
"""
from pathlib import Path
import argparse,hashlib,json,os,shutil,subprocess,sys,tempfile
ROOT=Path(__file__).resolve().parents[1]
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('kind',choices=['original','extended','plates']);p.add_argument('--output-directory',type=Path,required=True);a=p.parse_args();out=a.output_directory.resolve();out.mkdir(parents=True,exist_ok=True)
 with tempfile.TemporaryDirectory(prefix='paper-vii-guide-models-') as td:
  stage=Path(td)
  for name in ['source','checks']:shutil.copytree(ROOT/name,stage/name,ignore=shutil.ignore_patterns('runs','__pycache__','contracts'))
  env=dict(os.environ);env['PYTHONDONTWRITEBYTECODE']='1'
  commands={'original':['checks/verify_examples.py'],'extended':['checks/verify_extended.py'],'plates':['source/generate_graphics.py','source/generate_extensions.py']}[a.kind]
  for rel in commands:
   result=subprocess.run([sys.executable,rel],cwd=stage,env=env,check=True)
  if a.kind!='plates':
   name='EXACT_CHECKS.json' if a.kind=='original' else 'EXTENDED_CHECKS.json';shutil.copy2(stage/'checks'/name,out/name)
  else:
   rows=[]
   for directory in ['graphics','graphics_extended']:
    for generated in sorted((stage/directory).glob('*.tex')):
     original=ROOT/directory/generated.name;rows.append({'path':str(original.relative_to(ROOT)),'expected_sha256':sha(original),'regenerated_sha256':sha(generated),'byte_identical':original.read_bytes()==generated.read_bytes()})
   report={'status':'PASS' if all(r['byte_identical'] for r in rows) else 'MISMATCH','plate_count':len(rows),'exact_regeneration':all(r['byte_identical'] for r in rows),'scope':'Deterministic Python regeneration of all specified TikZ plates. Geometry samples are presentation data, not analytic proof.','plates':rows}
   (out/'PLATE_REPLAY.json').write_text(json.dumps(report,indent=2)+'\n')
   if report['status']!='PASS':raise SystemExit('Generated plate differs from canonical source.')
   print('PASS:',len(rows),'vector plates regenerated byte identically.')
if __name__=='__main__':main()
