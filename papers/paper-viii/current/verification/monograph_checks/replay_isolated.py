#!/usr/bin/env python3
"""Bounded replay of unchanged archival code in an isolated disposable copy.

Only report construction is new. Source mathematics, source tests and source
manifests are copied byte for byte. No Lean or device timing is executed.
"""
from __future__ import annotations
import argparse, hashlib, importlib.util, json, os, shutil, subprocess, sys, tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]

def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def write(p, value): p.write_text(json.dumps(value, indent=2)+"\n")

def command(argv, cwd, out, log):
    env=os.environ.copy(); env['PYTHONDONTWRITEBYTECODE']='1'; env['PYTEST_DISABLE_PLUGIN_AUTOLOAD']='1'
    r=subprocess.run(argv,cwd=cwd,env=env,text=True,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
    (out/log).write_text(r.stdout)
    print(r.stdout)
    if r.returncode: raise RuntimeError(f'{argv!r} exited {r.returncode}; see {log}')
    return {'argv':argv,'exit_code':r.returncode,'log':log,'log_sha256':sha(out/log)}

def main():
    p=argparse.ArgumentParser(); p.add_argument('mode',choices=['integrity','static','unit','original','sixth','fifth','structured','test-functions','pytest','sympy','portable','vectors']);p.add_argument('--out',type=Path,required=True);a=p.parse_args()
    out=a.out.resolve();out.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='paper_viii_bounded_replay_') as td:
        stage=Path(td)
        shutil.copytree(ROOT/'source',stage/'source')
        shutil.copytree(ROOT/'verification/checks',stage/'verification/checks')
        originals={p.relative_to(ROOT).as_posix():sha(p) for p in (ROOT/'source').rglob('*') if p.is_file()}
        assert all(sha(stage/rel)==h for rel,h in originals.items())
        if a.mode=='pytest':
            S=stage/'source/strengthened/PSC_Paper_VIII_Strengthened_Annals_Edition_Package'
            env=os.environ.copy();env['PYTHONPATH']=os.pathsep.join([str(S),str(S/'legacy')]);env['PYTHONDONTWRITEBYTECODE']='1';env['PYTEST_DISABLE_PLUGIN_AUTOLOAD']='1'
            argv=[sys.executable,'-m','pytest','-q','-p','no:cacheprovider','--junitxml='+str(out/'pytest.xml'),str(S/'legacy/tests'),str(S/'verification/test_strengthened.py')]
            r=subprocess.run(argv,cwd=S,env=env,text=True,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
            (out/'pytest.log').write_text(r.stdout); print(r.stdout)
            if r.returncode:raise RuntimeError(f'Actual pytest exited {r.returncode}')
            xml=ET.parse(out/'pytest.xml').getroot()
            suites=list(xml.iter('testsuite'))
            counts={k:sum(int(s.get(k,0)) for s in suites) for k in ['tests','failures','errors','skipped']}
            assert counts == {'tests':34,'failures':0,'errors':0,'skipped':0}, counts
            result={'status':'PASS','cases':counts['tests'],'junit_counts':counts,'command':argv,'software':'Actual pytest session, plugin autoload and cacheprovider disabled. Unchanged archival tests in isolated copy.','log_sha256':sha(out/'pytest.log')}
        elif a.mode in ['sympy','portable','vectors']:
            guide=stage/'editable/visual_guide';shutil.copytree(ROOT/'editable/visual_guide',guide)
            original_guide={p.relative_to(ROOT).as_posix():sha(p) for p in (ROOT/'editable/visual_guide').rglob('*.py') if p.is_file()}
            assert all(sha(stage/rel)==h for rel,h in original_guide.items())
            if a.mode=='vectors':
                commands=[command([sys.executable,str(guide/'source'/n)],guide,out,n+'.log') for n in ['generate_graphics.py','generate_extensions.py']]
                paths=sorted((guide/'graphics').glob('*.tex')); assert len(paths)==30
                compare=[{'name':q.name,'generated_sha256':sha(q),'delivered_sha256':sha(ROOT/'editable/visual_guide/graphics'/q.name),'bytes':q.stat().st_size,'matches_delivered':sha(q)==sha(ROOT/'editable/visual_guide/graphics'/q.name)} for q in paths]
                shutil.copytree(guide/'graphics',out/'generated_graphics')
                result={'status':'PASS','scope':'Thirty deterministic finite-model vector plates generated by unchanged Python/SymPy code. These sample declared formulas, not hardware timing. Comparison reports authored layout deviations explicitly.','vector_plates':30,'plate_comparison':compare,'commands':commands}
            else:
                filename='verify_examples.py' if a.mode=='sympy' else 'verify_portable.py'
                reportname='EXACT_CHECKS.json' if a.mode=='sympy' else 'PORTABLE_CHECKS.json'
                rec=command([sys.executable,str(guide/'checks'/filename)],guide,out,a.mode+'.log')
                result=json.loads((guide/'checks'/reportname).read_text());result['execution']=rec
                if a.mode=='sympy':assert result['checks_passed']==190 and len(result['invalid_controls_rejected'])==11
                else:assert result['positive_assertions']==208 and result['negative_controls_rejected']==15
            assert all(sha(ROOT/rel)==h for rel,h in original_guide.items())
        else:
            command([sys.executable,str(stage/'verification/checks/replay.py'),a.mode,'--out',str(out/'archival_result.json')],stage,out,'archival.log')
            result=json.loads((out/'archival_result.json').read_text())
        # The raw delivered input trees are never written by the isolated replay.
        assert all(sha(ROOT/rel)==h for rel,h in originals.items())
        result['isolation']={'source_files':len(originals),'copies_before_run_match':True,'delivered_source_after_run_matches':True,'temporary_copy_removed':True}
        write(out/'result.json',result)
        print('PASS:',a.mode)
if __name__=='__main__':main()
