"""Replay inherited finite evidence in temporary copies, preserving all inputs."""
from pathlib import Path
from tempfile import TemporaryDirectory
from datetime import datetime, timezone
import hashlib, json, os, shutil, subprocess, sys, time
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[3]
DEPENDENCIES = Path('/workspace/scratch/de82c13900d1/special_work/verification_dependencies')
OUTPUT = ROOT / sys.argv[1]
OUTPUT.mkdir(parents=True, exist_ok=True)
started = datetime.now(timezone.utc).isoformat()
start_clock = time.monotonic()
ignore = shutil.ignore_patterns('__pycache__', '.pytest_cache', '*.pyc')


def run(args, cwd, env):
    before = time.monotonic()
    proc = subprocess.run(args, cwd=cwd, env=env, text=True, capture_output=True, timeout=150)
    return {'argv': args, 'exit_code': proc.returncode, 'runtime_seconds': time.monotonic()-before,
            'stdout': proc.stdout, 'stderr': proc.stderr}


with TemporaryDirectory(prefix='paper_ii_checks_', dir='/workspace/scratch/963fbb80f50e/paper2_work') as td:
    temporary = Path(td)
    canonical = temporary / 'canonical_v1.2.1'
    for name in ('code', 'results'):
        shutil.copytree(ROOT/'source/canonical_v1.2.1'/name, canonical/name, ignore=ignore)
    visual = temporary/'visual_guide'
    for name in ('source', 'checks'):
        shutil.copytree(ROOT/'editable/visual_guide'/name, visual/name, ignore=ignore)
    figures = temporary/'traditional_figures'
    for name in ('figure_sources', 'fonts'):
        shutil.copytree(ROOT/'editable/traditional'/name, figures/name, ignore=ignore)

    env = os.environ.copy()
    env['PYTHONPATH'] = str(DEPENDENCIES)+os.pathsep+str(canonical/'code/python')
    env['PYTHONDONTWRITEBYTECODE'] = '1'
    canonical_run = run([sys.executable, '-m', 'pytest', '-q', '--junitxml='+str(temporary/'canonical.xml')], canonical/'code/python', env)
    exact_run = run([sys.executable, 'checks/verify_examples.py'], visual, env)
    atlas_run = run([sys.executable, 'source/generate_graphics.py'], visual, env)
    atlas_rows = []
    for graphic in sorted((visual/'graphics').glob('*.tex')):
        generated = graphic.read_bytes()
        original_visual = ROOT/'editable/visual_guide/graphics'/graphic.name
        original_traditional = ROOT/'editable/traditional/visual_graphics'/graphic.name
        atlas_rows.append({'name': graphic.name,
                           'sha256': hashlib.sha256(generated).hexdigest(),
                           'matches_visual_guide_bytes': generated == original_visual.read_bytes(),
                           'matches_traditional_atlas_bytes': generated == original_traditional.read_bytes()})
    atlas_match = len(atlas_rows) == 22 and all(row['matches_visual_guide_bytes'] and row['matches_traditional_atlas_bytes'] for row in atlas_rows)
    atlas_comparison = {'status': 'PASS' if atlas_match else 'FAIL', 'generated_graphic_count': len(atlas_rows),
                        'scope': 'Fresh generated bytes compared with both current editable copies, including the final weighted_multigraph footer line break.',
                        'graphics': atlas_rows}
    generator_code = "import sys;sys.path.insert(0,'figure_sources');import draw_matrix_visuals,draw_graph_visuals;draw_matrix_visuals.generate();draw_graph_visuals.generate();print('PASS: all 13 generators and their data assertions')"
    generator_run = run([sys.executable, '-c', generator_code], figures, env)
    suite = ET.parse(temporary/'canonical.xml').getroot().find('testsuite')
    canonical_summary = dict(suite.attrib)
    canonical_summary['tests'] = int(canonical_summary['tests'])
    canonical_summary['failures'] = int(canonical_summary['failures'])
    canonical_summary['errors'] = int(canonical_summary['errors'])
    canonical_summary['skipped'] = int(canonical_summary['skipped'])
    canonical_summary['cases'] = [{'class': c.get('classname'), 'name': c.get('name'),
                                  'runtime_seconds': float(c.get('time'))} for c in suite.findall('testcase')]
    exact = json.loads((visual/'checks/EXACT_CHECKS.json').read_text())
    matrix = json.loads((figures/'figure_sources/matrix_visual_data.json').read_text())
    graph = json.loads((figures/'figure_sources/graph_visuals_validation.json').read_text())
    status = 'PASS' if (all(item['exit_code'] == 0 for item in (canonical_run, exact_run, generator_run, atlas_run))
                        and canonical_summary['tests'] == 48 and exact['check_count'] == 118
                        and all(c['passed'] for c in exact['checks']) and len(matrix) == 6 and atlas_match) else 'FAIL'
    report = {'status': status, 'started_at_utc': started,
              'runtime_seconds': time.monotonic()-start_clock,
              'isolation': 'Every execution read temporary copies. Original source and recorded release evidence were not changed.',
              'canonical_suite': canonical_summary, 'visual_guide_exact_checks': exact,
              'main_figure_count': 13, 'atlas_source_regeneration': atlas_comparison, 'matrix_figure_data': matrix, 'graph_figure_validation': graph,
              'runs': {'canonical_tests': canonical_run, 'visual_exact_examples': exact_run, 'figure_generators': generator_run, 'atlas_generator': atlas_run},
              'arithmetic_domains': {'canonical_suite': 'Mixed exact integer/modular/SymPy arithmetic and floating NumPy residuals',
                                     'visual_guide': 'Exact integer, rational, symbolic, finite-field and modular checks',
                                     'main_figures': 'Exact integer/Fraction data alongside labelled floating norms and complex-coordinate approximations'},
              'non_claims': ['No universal theorem follows from the bounded tests alone.',
                             'No fresh Lean compiler replay was performed.',
                             'Visual-guide examples and main figures use distinct explicitly recorded models and finite ranges.']}
    (OUTPUT/'RUN_RESULT.json').write_text(json.dumps(report, indent=2)+'\n')
    print(f"{status}: {canonical_summary['tests']} canonical tests, {exact['check_count']} exact examples, 13 main generators, {len(atlas_rows)} matching atlas sources")
    if status != 'PASS':
        raise SystemExit(1)
