"""Sparse, exactly solvable operator-inference task proposed for v0.3.

The v0.2 task exposed a complete transition table for every primitive.  This
module instead exposes five affine-independent demonstrations for an operator
on a 625-state product space.  A finite-field affine solver can recover the
operator exactly, while an executor that only looks up observed table cells
cannot take even the first query step.

Only the demonstrations, a product-state start, and an anonymous slot word are
model inputs.  Operator parameters and attribute masks are audit metadata.
"""

