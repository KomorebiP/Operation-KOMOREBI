ProductState = tuple[int, ...]
IntMatrix = tuple[tuple[int, ...], ...]


def _hash(domain: str, payload: bytes) -> bytes:
    framed = (
        CONTEXT_SPLIT_NAMESPACE.encode("utf-8")
        + b"\x00"
        + domain.encode("utf-8")
        + b"\x00"
        + payload
    )
    return hashlib.sha256(framed).digest()


def _validate_state(state: Sequence[int]) -> ProductState:
    values = tuple(int(value) for value in state)
    if len(values) != N_ATTRIBUTES:
        raise ValueError(f"product state must have {N_ATTRIBUTES} attributes")
    if any(value < 0 or value >= FIELD_ORDER for value in values):
        raise ValueError(f"attribute values must be in 0..{FIELD_ORDER - 1}")
    return values


def encode_product_state(state: Sequence[int]) -> int:
    """Encode a visible attribute tuple as a stable integer in ``0..624``."""

    encoded = 0
    for value in _validate_state(state):
        encoded = encoded * FIELD_ORDER + value
    return encoded


def decode_product_state(index: int) -> ProductState:
    """Inverse of :func:`encode_product_state`."""

    value = int(index)
    if value < 0 or value >= N_PRODUCT_STATES:
        raise ValueError(f"state index must be in 0..{N_PRODUCT_STATES - 1}")
    attributes = [0] * N_ATTRIBUTES
    for position in range(N_ATTRIBUTES - 1, -1, -1):
        attributes[position] = value % FIELD_ORDER
        value //= FIELD_ORDER
    return tuple(attributes)


@lru_cache(maxsize=1)
def all_product_states() -> tuple[ProductState, ...]:
    return tuple(itertools.product(range(FIELD_ORDER), repeat=N_ATTRIBUTES))


def _identity_matrix() -> IntMatrix:
    return tuple(
        tuple(int(row == column) for column in range(N_ATTRIBUTES))
        for row in range(N_ATTRIBUTES)
    )


def _serialize_affine(matrix: IntMatrix, bias: ProductState) -> bytes:
    return bytes(value for row in matrix for value in row) + bytes(bias)


@dataclass(frozen=True)
class AffineMap:
    """A row-output affine map ``y = A x + b`` over GF(5)."""

    matrix: IntMatrix
    bias: ProductState

    def __post_init__(self) -> None:
        matrix = tuple(tuple(int(value) for value in row) for row in self.matrix)
        bias = _validate_state(self.bias)
        if len(matrix) != N_ATTRIBUTES or any(len(row) != N_ATTRIBUTES for row in matrix):
            raise ValueError(f"matrix must have shape ({N_ATTRIBUTES}, {N_ATTRIBUTES})")
        if any(value < 0 or value >= FIELD_ORDER for row in matrix for value in row):
            raise ValueError(f"matrix entries must be in 0..{FIELD_ORDER - 1}")
        object.__setattr__(self, "matrix", matrix)
        object.__setattr__(self, "bias", bias)

    def apply(self, state: Sequence[int]) -> ProductState:
        vector = _validate_state(state)
        return tuple(
            (sum(self.matrix[row][column] * vector[column] for column in range(N_ATTRIBUTES)) + self.bias[row])
            % FIELD_ORDER
            for row in range(N_ATTRIBUTES)
        )

    @property
    def fingerprint(self) -> str:
        return _hash("operator", _serialize_affine(self.matrix, self.bias)).hex()

    @property
    def write_mask(self) -> tuple[bool, ...]:
        identity = _identity_matrix()
        return tuple(
            self.matrix[row] != identity[row] or self.bias[row] != 0
            for row in range(N_ATTRIBUTES)
        )

    @property
    def update_read_mask(self) -> tuple[bool, ...]:
        """Inputs on which the update ``F(x)-x`` depends."""

        identity = _identity_matrix()
        return tuple(
            any(
                (self.matrix[row][column] - identity[row][column]) % FIELD_ORDER != 0
                for row in range(N_ATTRIBUTES)
            )
            for column in range(N_ATTRIBUTES)
        )

    @property
    def dependency_mask(self) -> tuple[tuple[bool, ...], ...]:
        """Direct input dependencies of each output attribute."""

        return tuple(
            tuple(self.matrix[row][column] % FIELD_ORDER != 0 for column in range(N_ATTRIBUTES))
            for row in range(N_ATTRIBUTES)
        )

    @property
    def preserved_mask(self) -> tuple[bool, ...]:
        identity = _identity_matrix()
        return tuple(
            self.matrix[row] == identity[row] and self.bias[row] == 0
            for row in range(N_ATTRIBUTES)
        )

    @property
    def write_attribute(self) -> int:
        indices = [index for index, enabled in enumerate(self.write_mask) if enabled]
        if len(indices) != 1:
            raise ValueError("map does not have exactly one written attribute")
        return indices[0]

    @property
    def source_attribute(self) -> int:
        indices = [index for index, enabled in enumerate(self.update_read_mask) if enabled]
        if len(indices) != 1:
            raise ValueError("map does not have exactly one update-read attribute")
        return indices[0]


@dataclass(frozen=True)
class Demonstration:
    source: ProductState
    target: ProductState

    def __post_init__(self) -> None:
        object.__setattr__(self, "source", _validate_state(self.source))
        object.__setattr__(self, "target", _validate_state(self.target))


@dataclass(frozen=True)
class SparseContext:
    """Immutable context truth and its immutable sparse observations."""

    context_id: str
    fingerprint: str
    family: str
    split: str
    operators: tuple[AffineMap, ...]
    demonstrations: tuple[tuple[Demonstration, ...], ...]

    def __post_init__(self) -> None:
        if self.family not in OPERATOR_FAMILIES:
            raise ValueError(f"unknown operator family: {self.family}")
        if self.split not in CONTEXT_SPLITS:
            raise ValueError(f"unknown context split: {self.split}")
        if len(self.operators) != N_OPERATORS:
            raise ValueError(f"a context must contain {N_OPERATORS} operators")
        if len(self.demonstrations) != N_OPERATORS:
            raise ValueError(f"a context must contain {N_OPERATORS} demo sets")
        if any(len(demos) != DEMONSTRATIONS_PER_OPERATOR for demos in self.demonstrations):
            raise ValueError(
                f"each operator must have {DEMONSTRATIONS_PER_OPERATOR} demonstrations"
            )

    @property
    def write_masks(self) -> tuple[tuple[bool, ...], ...]:
        return tuple(operator.write_mask for operator in self.operators)

    @property
    def update_read_masks(self) -> tuple[tuple[bool, ...], ...]:
        return tuple(operator.update_read_mask for operator in self.operators)

    @property
    def dependency_masks(self) -> tuple[tuple[tuple[bool, ...], ...], ...]:
        return tuple(operator.dependency_mask for operator in self.operators)

    @property
    def preserved_masks(self) -> tuple[tuple[bool, ...], ...]:
        return tuple(operator.preserved_mask for operator in self.operators)


@dataclass(frozen=True)
class _Catalog:
    contexts: tuple[SparseContext, ...]
    by_id: Mapping[str, SparseContext]
    by_split: Mapping[str, tuple[SparseContext, ...]]
    digest: str


def _inverse_mod(matrix: np.ndarray) -> np.ndarray:
    """Exact Gauss-Jordan inverse over the task's prime field."""

    array = np.asarray(matrix, dtype=np.int64) % FIELD_ORDER
    if array.ndim != 2 or array.shape[0] != array.shape[1]:
        raise ValueError("matrix must be square")
    size = array.shape[0]
    augmented = np.concatenate((array.copy(), np.eye(size, dtype=np.int64)), axis=1)
    for column in range(size):
        pivots = np.flatnonzero(augmented[column:, column] % FIELD_ORDER)
        if pivots.size == 0:
            raise ValueError("matrix is singular over GF(5)")
        pivot = column + int(pivots[0])
        if pivot != column:
            augmented[[column, pivot]] = augmented[[pivot, column]]
        inverse_pivot = pow(int(augmented[column, column]), -1, FIELD_ORDER)
        augmented[column] = (augmented[column] * inverse_pivot) % FIELD_ORDER
        for row in range(size):
            if row == column:
                continue
            factor = int(augmented[row, column]) % FIELD_ORDER
            if factor:
                augmented[row] = (augmented[row] - factor * augmented[column]) % FIELD_ORDER
    return augmented[:, size:] % FIELD_ORDER


def _hash_field_stream(seed: bytes) -> Iterable[int]:
    counter = 0
    while True:
        digest = _hash("frame", seed + counter.to_bytes(8, "big"))
        for value in digest:
            yield value % FIELD_ORDER
        counter += 1


def _demo_frame(context_fingerprint: str, slot: int) -> tuple[ProductState, ...]:
    stream = iter(_hash_field_stream(bytes.fromhex(context_fingerprint) + bytes((slot,))))
    origin = tuple(next(stream) for _ in range(N_ATTRIBUTES))
    while True:
        basis_array = np.asarray(
            [[next(stream) for _ in range(N_ATTRIBUTES)] for _ in range(N_ATTRIBUTES)],
            dtype=np.int64,
        )
        try:
            _inverse_mod(basis_array)
        except ValueError:
            continue
        break
    points = [origin]
    origin_array = np.asarray(origin, dtype=np.int64)
    for row in basis_array:
        points.append(tuple(int(value) for value in (origin_array + row) % FIELD_ORDER))
    return tuple(points)


def _shear_candidate_operators() -> tuple[AffineMap, ...]:
    candidates: list[AffineMap] = []
    identity = np.eye(N_ATTRIBUTES, dtype=np.int64)
    for target in range(N_ATTRIBUTES):
        for source in range(N_ATTRIBUTES):
            if source == target:
                continue
            for coefficient in range(1, FIELD_ORDER):
                for translation in range(FIELD_ORDER):
                    matrix = identity.copy()
                    matrix[target, source] = coefficient
                    bias = np.zeros(N_ATTRIBUTES, dtype=np.int64)
                    bias[target] = translation
                    candidates.append(
                        AffineMap(
                            matrix=tuple(tuple(int(value) for value in row) for row in matrix),
                            bias=tuple(int(value) for value in bias),
                        )
                    )
    if len(candidates) != 240:
        raise AssertionError("unexpected primitive catalog size")
    return tuple(sorted(candidates, key=lambda operator: operator.fingerprint))


def _monomial_candidate_operators() -> tuple[AffineMap, ...]:
    """Return 240 frozen signed-monomial affine primitives.

    Every one of the 24 coordinate permutations receives ten deterministic
    sign/translation variants.  Bias codes are a bijective affine traversal of
    the first 240 catalog indices modulo 625, so no two selected affine maps can
    coincide.  The selected finite catalog, rather than the full 240,000-member
    signed-monomial family, is what the frozen context partition covers.
    """

    candidates: list[AffineMap] = []
    for permutation_index, permutation in enumerate(itertools.permutations(range(N_ATTRIBUTES))):
        for variant in range(10):
            catalog_index = permutation_index * 10 + variant
            sign_digest = _hash(
                "monomial-sign",
                bytes(permutation) + variant.to_bytes(2, "big"),
            )
            signs = tuple(1 if (sign_digest[index] & 1) == 0 else FIELD_ORDER - 1 for index in range(N_ATTRIBUTES))
            matrix_array = np.zeros((N_ATTRIBUTES, N_ATTRIBUTES), dtype=np.int64)
            for output_attribute, input_attribute in enumerate(permutation):
                matrix_array[output_attribute, input_attribute] = signs[output_attribute]
            # 137 is coprime to 625, making these codes unique.
            bias_code = (137 * catalog_index + 43) % N_PRODUCT_STATES
            bias = decode_product_state(bias_code)
            candidates.append(
                AffineMap(
                    matrix=tuple(
                        tuple(int(value) for value in row) for row in matrix_array
                    ),
                    bias=bias,
                )
            )
    if len(candidates) != 240 or len({operator.fingerprint for operator in candidates}) != 240:
        raise AssertionError("unexpected signed-monomial primitive catalog")
    return tuple(sorted(candidates, key=lambda operator: operator.fingerprint))


def _candidate_operators(family: str) -> tuple[AffineMap, ...]:
    if family == SHEAR_FAMILY:
        return _shear_candidate_operators()
    if family == MONOMIAL_FAMILY:
        return _monomial_candidate_operators()
    raise ValueError(f"family must be one of {OPERATOR_FAMILIES}")


def _context_fingerprint(family: str, operators: tuple[AffineMap, ...]) -> str:
    payload = family.encode("utf-8") + b"\x00" + b"".join(
        bytes.fromhex(operator.fingerprint) for operator in operators
    )
    return _hash("context", payload).hex()


@lru_cache(maxsize=None)
def _catalog(family: str = SHEAR_FAMILY) -> _Catalog:
    normalized_family = str(family).lower()
    if normalized_family not in OPERATOR_FAMILIES:
        raise ValueError(f"family must be one of {OPERATOR_FAMILIES}")
    operators = _candidate_operators(normalized_family)
    provisional: list[tuple[str, tuple[AffineMap, ...]]] = []
    for offset in range(0, len(operators), N_OPERATORS):
        pair = operators[offset : offset + N_OPERATORS]
        fingerprint = _context_fingerprint(normalized_family, pair)
        provisional.append((fingerprint, pair))
    provisional.sort(key=lambda item: item[0])

    cut_train = CONTEXT_SPLIT_COUNTS["train"]
    cut_dev = cut_train + CONTEXT_SPLIT_COUNTS["dev"]
    contexts: list[SparseContext] = []
    for index, (fingerprint, pair) in enumerate(provisional):
        split = "train" if index < cut_train else "dev" if index < cut_dev else "test"
        context_id = f"sac-{normalized_family}-{fingerprint[:24]}"
        demo_sets: list[tuple[Demonstration, ...]] = []
        for slot, operator in enumerate(pair):
            inputs = _demo_frame(fingerprint, slot)
            demo_sets.append(
                tuple(Demonstration(source=source, target=operator.apply(source)) for source in inputs)
            )
        contexts.append(
            SparseContext(
                context_id=context_id,
                fingerprint=fingerprint,
                family=normalized_family,
                split=split,
                operators=pair,
                demonstrations=tuple(demo_sets),
            )
        )

    by_id = MappingProxyType({context.context_id: context for context in contexts})
    by_split = MappingProxyType(
        {
            split: tuple(context for context in contexts if context.split == split)
            for split in CONTEXT_SPLITS
        }
    )
    manifest = b"".join(
        bytes.fromhex(context.fingerprint)
        + bytes((CONTEXT_SPLITS.index(context.split),))
        + b"".join(bytes.fromhex(operator.fingerprint) for operator in context.operators)
        + bytes(
            value
            for demo_set in context.demonstrations
            for demonstration in demo_set
            for state in (demonstration.source, demonstration.target)
            for value in state
        )
        for context in contexts
    )
    return _Catalog(
        contexts=tuple(contexts),
        by_id=by_id,
        by_split=by_split,
        digest=hashlib.sha256(manifest).hexdigest(),
    )


def contexts_in_split(
    split: str, family: str = SHEAR_FAMILY
) -> tuple[SparseContext, ...]:
    normalized = str(split).lower()
    if normalized not in CONTEXT_SPLITS:
        raise ValueError(f"split must be one of {CONTEXT_SPLITS}")
    normalized_family = str(family).lower()
    if normalized_family not in OPERATOR_FAMILIES:
        raise ValueError(f"family must be one of {OPERATOR_FAMILIES}")
    return _catalog(normalized_family).by_split[normalized]


def get_context(context_id: str) -> SparseContext:
    for family in OPERATOR_FAMILIES:
        context = _catalog(family).by_id.get(context_id)
        if context is not None:
            return context
    raise ValueError(f"unknown sparse context: {context_id}")


def context_split_manifest(family: str = SHEAR_FAMILY) -> Mapping[str, str]:
    """Return a read-only mapping from every frozen context id to its split."""

    return MappingProxyType(
        {context.context_id: context.split for context in _catalog(family).contexts}
    )


@dataclass(frozen=True)
class ContextSplitAudit:
    namespace: str
    family: str
    observed_counts: Mapping[str, int]
    context_pairwise_intersections: Mapping[str, int]
    operator_pairwise_intersections: Mapping[str, int]
    unique_contexts: bool
    unique_operators: bool
    complete: bool
    digest: str

    @property
    def passed(self) -> bool:
        return bool(
            dict(self.observed_counts) == dict(CONTEXT_SPLIT_COUNTS)
            and all(value == 0 for value in self.context_pairwise_intersections.values())
            and all(value == 0 for value in self.operator_pairwise_intersections.values())
            and self.unique_contexts
            and self.unique_operators
            and self.complete
        )


def audit_context_splits(family: str = SHEAR_FAMILY) -> ContextSplitAudit:
    normalized_family = str(family).lower()
    catalog = _catalog(normalized_family)
    context_sets = {
        split: {context.fingerprint for context in catalog.by_split[split]}
        for split in CONTEXT_SPLITS
    }
    operator_sets = {
        split: {
            operator.fingerprint
            for context in catalog.by_split[split]
            for operator in context.operators
        }
        for split in CONTEXT_SPLITS
    }
    pairs = (("train", "dev"), ("train", "test"), ("dev", "test"))
    context_intersections = {
        f"{first}_{second}": len(context_sets[first] & context_sets[second])
        for first, second in pairs
    }
    operator_intersections = {
        f"{first}_{second}": len(operator_sets[first] & operator_sets[second])
        for first, second in pairs
    }
    total_contexts = sum(len(values) for values in context_sets.values())
    total_operators = sum(len(values) for values in operator_sets.values())
    return ContextSplitAudit(
        namespace=CONTEXT_SPLIT_NAMESPACE,
        family=normalized_family,
        observed_counts=MappingProxyType(
            {split: len(context_sets[split]) for split in CONTEXT_SPLITS}
        ),
        context_pairwise_intersections=MappingProxyType(context_intersections),
        operator_pairwise_intersections=MappingProxyType(operator_intersections),
        unique_contexts=len(set().union(*context_sets.values())) == total_contexts,
        unique_operators=len(set().union(*operator_sets.values())) == total_operators,
        complete=total_contexts == 120 and total_operators == 240,
        digest=catalog.digest,
    )


def _factor_values(operator: AffineMap, family: str) -> dict[str, str]:
    if family == SHEAR_FAMILY:
        target = operator.write_attribute
        source = operator.source_attribute
        return {
            "target_attribute": str(target),
            "source_attribute": str(source),
            "coefficient": str(operator.matrix[target][source]),
            "translation": str(operator.bias[target]),
        }
    if family == MONOMIAL_FAMILY:
        matrix = np.asarray(operator.matrix, dtype=np.int64) % FIELD_ORDER
        permutation = tuple(int(np.flatnonzero(matrix[row])[0]) for row in range(N_ATTRIBUTES))
        signs = tuple(
            "+" if int(matrix[row, permutation[row]]) == 1 else "-"
            for row in range(N_ATTRIBUTES)
        )
        values = {
            "permutation": ",".join(str(value) for value in permutation),
            "sign_pattern": "".join(signs),
        }
        values.update(
            {f"bias_attribute_{index}": str(value) for index, value in enumerate(operator.bias)}
        )
        return values
    raise ValueError(f"family must be one of {OPERATOR_FAMILIES}")


def factor_combination_audit(family: str = SHEAR_FAMILY) -> dict[str, object]:
    """JSON-safe exact factor-combination and marginal split report.

    The defensible split claim is that complete primitive factor combinations
    (equivalently primitive maps) are held out.  Individual factor values form
    a deliberately shared vocabulary and may recur across all three splits.
    """

    normalized_family = str(family).lower()
    combinations: dict[str, set[tuple[tuple[str, str], ...]]] = {}
    marginals: dict[str, dict[str, dict[str, int]]] = {}
    for split in CONTEXT_SPLITS:
        split_combinations: set[tuple[tuple[str, str], ...]] = set()
        split_marginals: dict[str, dict[str, int]] = {}
        for context in contexts_in_split(split, normalized_family):
            for operator in context.operators:
                factors = _factor_values(operator, normalized_family)
                split_combinations.add(tuple(sorted(factors.items())))
                for factor, value in factors.items():
                    counts = split_marginals.setdefault(factor, {})
                    counts[value] = counts.get(value, 0) + 1
        combinations[split] = split_combinations
        marginals[split] = {
            factor: dict(sorted(counts.items()))
            for factor, counts in sorted(split_marginals.items())
        }
    pairs = (("train", "dev"), ("train", "test"), ("dev", "test"))
    intersections = {
        f"{first}_{second}": len(combinations[first] & combinations[second])
        for first, second in pairs
    }
    return {
        "family": normalized_family,
        "claim_boundary": (
            "held-out complete primitive-factor combinations with a shared marginal factor vocabulary"
        ),
        "combination_counts": {
            split: len(combinations[split]) for split in CONTEXT_SPLITS
        },
        "pairwise_combination_intersections": intersections,
        "marginal_counts": marginals,
        "passed": all(value == 0 for value in intersections.values())
        and sum(len(values) for values in combinations.values()) == 240,
    }


def context_audit_record(family: str = SHEAR_FAMILY) -> dict[str, object]:
    """JSON-serializable, fail-closed context/closure receipt for runners."""

    audit = audit_context_splits(family)
    closure = train_closure_audit_record(family)
    bounded_novelty_passed = closure[
        "bounded_within_context_training_support"
    ]["operator_novelty_passed"]
    return {
        "namespace": audit.namespace,
        "family": audit.family,
        "expected_counts": dict(CONTEXT_SPLIT_COUNTS),
        "observed_counts": dict(audit.observed_counts),
        "context_pairwise_intersections": dict(audit.context_pairwise_intersections),
        "operator_pairwise_intersections": dict(audit.operator_pairwise_intersections),
        "unique_contexts": audit.unique_contexts,
        "unique_operators": audit.unique_operators,
        "complete": audit.complete,
        "digest": audit.digest,
        "factor_combinations": factor_combination_audit(family),
        "train_closure": closure,
        "primitive_split_disjointness_passed": audit.passed,
        "bounded_operator_novelty_passed": bounded_novelty_passed,
        # Generic consumers that check only `passed` must reject shear rather
        # than mistaking direct fingerprint disjointness for train novelty.
        "passed": audit.passed and bounded_novelty_passed,
    }


