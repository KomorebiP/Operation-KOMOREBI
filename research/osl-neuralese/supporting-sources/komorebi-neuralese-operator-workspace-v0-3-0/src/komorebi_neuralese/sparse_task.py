from types import MappingProxyType
from typing import Iterable, Mapping, Sequence

import numpy as np


FIELD_ORDER = 5
N_ATTRIBUTES = 4
N_OPERATORS = 2
N_PRODUCT_STATES = FIELD_ORDER**N_ATTRIBUTES
DEMONSTRATIONS_PER_OPERATOR = N_ATTRIBUTES + 1

SHEAR_FAMILY = "shear"
MONOMIAL_FAMILY = "monomial"
OPERATOR_FAMILIES = (SHEAR_FAMILY, MONOMIAL_FAMILY)

FOCAL_ATTRIBUTE = 0
PAYLOAD_ATTRIBUTES = (1, 2, 3)

KEY_ARM = "sparse_compositional_terminal"
PRIMITIVE_DIAGNOSTIC_ARM = "primitive_diagnostic"
TASK_ARMS = (KEY_ARM, PRIMITIVE_DIAGNOSTIC_ARM)

# The developmental Stage-B design samples only these word lengths.  Closure
# auditing distinguishes collisions inside this actually supported training
# language from the much broader group generated by pooling primitives across
# otherwise independent contexts.
TRAINING_WORD_LENGTHS = (2, 3, 4)
