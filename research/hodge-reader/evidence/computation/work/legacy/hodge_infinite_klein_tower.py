from __future__ import annotations

import json
import math
from pathlib import Path

import sympy as sp
from sympy.matrices.normalforms import smith_normal_form
from sympy.polys.domains import ZZ

OUT = Path('/mnt/data/Hodge_Infinite_Klein_Tower_VERIFICATION.json')
BASE_DEGREE = 33
ALPHA = (7, 19, 28, 10, 13, 22)

# Projective character-lattice matrix of the degree-33 Klein--Delsarte map.
D = sp.Matrix([
    [16, 1, -2, 4, -8],
    [-8, 16, 1, -2, 4],
    [4, -8, 16, 1, -2],
    [-2, 4, -8, 16, 1],
    [1, -2, 4, -8, 16],
])


def units(n: int) -> list[int]:
    return [u for u in range(1, n) if math.gcd(u, n) == 1]


def least_positive(x: int, n: int) -> int:
    r = x % n
    return n if r == 0 else r


def orbit_for_k(k: int) -> set[tuple[int, ...]]:
    m = BASE_DEGREE * k
    return {
        tuple(least_positive(u * k * a, m) for a in ALPHA)
        for u in units(m)
    }


def hodge_level(packet: tuple[int, ...], modulus: int) -> int:
    return sum(packet) // modulus


def sample_record(k: int) -> dict:
    m = BASE_DEGREE * k
    orbit = orbit_for_k(k)
    levels = sorted({hodge_level(a, m) for a in orbit})
    scaled_D = k * D
    snf = smith_normal_form(scaled_D, domain=ZZ)
    snf_diag = [abs(int(x)) for x in snf.diagonal()]

    # Pulling back a Fermat residue numerator x^(alpha-1) under z_i=x_i^k
    # multiplies the old exponent by k and contributes k-1 from the volume form.
    old_numerator = [a - 1 for a in ALPHA]
    pulled_numerator = [k * e + (k - 1) for e in old_numerator]
    expected_numerator = [k * a - 1 for a in ALPHA]

    return {
        'k': k,
        'source_degree': m,
        'scaled_character': [k * a for a in ALPHA],
        'orbit_size': len(orbit),
        'hodge_levels': levels,
        'all_orbit_sums': sorted({sum(a) for a in orbit}),
        'projective_power_map_degree': k**5,
        'composed_klein_map_degree': (k**5) * (33**4),
        'scaled_lattice_smith_diagonal': snf_diag,
        'residue_pullback_exponents': pulled_numerator,
        'expected_scaled_character_minus_one': expected_numerator,
        'checks': {
            'entries_are_nonzero_and_below_modulus': all(0 < k * a < m for a in ALPHA),
            'orbit_size_is_20': len(orbit) == 20,
            'all_orbit_packets_are_middle_hodge': levels == [3],
            'all_orbit_sums_are_3m': {sum(a) for a in orbit} == {3 * m},
            'residue_pullback_scales_character': pulled_numerator == expected_numerator,
            'scaled_snf_is_k_33k_33k_33k_33k': snf_diag == [k, 33*k, 33*k, 33*k, 33*k],
        },
    }


records = [sample_record(k) for k in range(1, 13)]

# Exact semigroup/composition identities for the coordinate-power maps.
composition_checks = []
for r, s in [(2, 3), (3, 5), (4, 7), (6, 11)]:
    # On residue exponents: first scale by r and then by s.
    sequential = [s * (r * a - 1) + (s - 1) for a in ALPHA]
    # Be careful: after first pullback the character is r*a, so numerator is r*a-1.
    direct = [(r * s) * a - 1 for a in ALPHA]
    composition_checks.append({
        'r': r,
        's': s,
        'sequential_exponents': sequential,
        'direct_exponents': direct,
        'matches': sequential == direct,
        'degree_matches': (r**5) * (s**5) == (r*s)**5,
    })

# Tate-suspension samples: append complementary pairs (b,m-b).
tate_samples = []
for k, r in [(1, 1), (2, 2), (5, 3)]:
    m = 33*k
    packet = [k*a for a in ALPHA]
    pairs = []
    for j in range(r):
        b = 1 + ((7*j + 3) % (m - 1))
        pairs.extend([b, m-b])
    enlarged = packet + pairs
    p = 2 + r
    tate_samples.append({
        'k': k,
        'r': r,
        'modulus': m,
        'dimension': 4 + 2*r,
        'packet': enlarged,
        'sum': sum(enlarged),
        'expected_sum': (p+1)*m,
        'middle_hodge_balance': sum(enlarged) == (p+1)*m,
    })

checks = {
    'base_lattice_snf': [abs(int(x)) for x in smith_normal_form(D, domain=ZZ).diagonal()] == [1, 33, 33, 33, 33],
    'all_sample_tower_checks': all(all(rec['checks'].values()) for rec in records),
    'all_composition_checks': all(row['matches'] and row['degree_matches'] for row in composition_checks),
    'all_tate_suspension_checks': all(row['middle_hodge_balance'] for row in tate_samples),
}

result = {
    'title': 'Infinite Klein--Delsarte conductor tower for Fermat Hodge packets',
    'base_degree': BASE_DEGREE,
    'base_character': list(ALPHA),
    'base_packet_dimension': 20,
    'theorem_summary': (
        'For every k>=1, the rational Galois packet generated by k*alpha in '
        'H^4_prim(X_{33k}^4,Q) is the pullback of the algebraic degree-33 packet '
        'under the coordinate-wise k-th power map, hence is algebraic.'
    ),
    'records': records,
    'composition_checks': composition_checks,
    'tate_suspension_samples': tate_samples,
    'checks': checks,
    'passed': all(checks.values()),
}

OUT.write_text(json.dumps(result, indent=2), encoding='utf-8')
print(json.dumps(result, indent=2))
if not result['passed']:
    raise SystemExit('verification failed')
